export const getCityByName = (name) => {
  const target = normalizeLocationName(name);
  return turkishCities.find((city) => normalizeLocationName(city.name) === target) || null;
};

export const getAllCities = () => {
  return [...new Set(turkishCities.map((city) => decodeMojibakeText(city.name)).filter(Boolean))].sort((a, b) =>
    a.localeCompare(b, "tr")
  );
};

export const getDistrictsByCity = (cityName) => {
  const target = normalizeLocationName(cityName);
  const entry = Object.entries(cityDistricts).find(([city]) => normalizeLocationName(city) === target);

  if (!entry) {
    return [];
  }

  return [...new Set(entry[1].map((district) => decodeMojibakeText(district)).filter(Boolean))].sort((a, b) =>
    a.localeCompare(b, "tr")
  );
};

export function decodeMojibakeText(value) {
  const input = String(value ?? "").trim();

  if (!input) {
    return "";
  }

  try {
    return decodeURIComponent(escape(input));
  } catch {
    return input;
  }
}

export function normalizeLocationName(value) {
  return decodeMojibakeText(value)
    .toLocaleLowerCase("tr")
    .replace(/ı/g, "i")
    .replace(/ç/g, "c")
    .replace(/ğ/g, "g")
    .replace(/ö/g, "o")
    .replace(/ş/g, "s")
    .replace(/ü/g, "u")
    .replace(/\s+/g, " ")
    .trim();
}

